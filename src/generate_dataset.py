# generate_dataset.py
#
# Generates a SIMULATED (synthetic) dataset for the project:
# "ML & DL Based Models to Predict Effects of Light and Noise on Cognitive Tasks"
#
# WHY THIS EXISTS:
# The real IMPACT dataset (Markov et al., 2024) is request-only from the
# original researchers and was not available within the project deadline.
# This script creates a substitute dataset whose light/noise effects are
# based on directions reported in published literature (see README notes),
# so the ML/DL pipeline can be built, trained, and evaluated honestly.
#
# IMPORTANT: This is NOT real human data. Every number produced by this
# script is generated by a formula we control. Any "results" from models
# trained on this data describe how well the models recovered the
# KNOWN, INTENTIONALLY-INSERTED relationships -- not a real scientific
# finding about human cognition. This must be disclosed in the report.

import numpy as np
import pandas as pd

RANDOM_SEED = 42
N_PARTICIPANTS = 24
TRIALS_PER_CONDITION = 25
CONDITIONS = ["Baseline", "Light", "Noise", "Both"]

rng = np.random.default_rng(RANDOM_SEED)


def make_participants(n):
    ages = rng.integers(18, 30, size=n)
    genders = rng.choice(["Male", "Female"], size=n, p=[0.6, 0.4])
    baseline_speed = rng.normal(loc=550, scale=60, size=n)
    return pd.DataFrame({
        "participant_id": [f"P{str(i+1).zfill(2)}" for i in range(n)],
        "age": ages,
        "gender": genders,
        "baseline_speed_ms": baseline_speed,
    })


def light_effect_ms(light_lux):
    optimal = 500
    deviation = (light_lux - optimal) / 100
    return 8 * (deviation ** 2)


def noise_effect_ms(noise_db):
    threshold = 45
    excess = np.maximum(noise_db - threshold, 0)
    return 3.5 * excess


def simulate_trials(participants_df):
    rows = []
    for _, p in participants_df.iterrows():
        for condition in CONDITIONS:
            for trial_num in range(1, TRIALS_PER_CONDITION + 1):

                if condition == "Baseline":
                    light_lux = rng.normal(480, 40)
                    noise_db = rng.normal(38, 4)
                elif condition == "Light":
                    light_lux = rng.normal(1100, 100)
                    noise_db = rng.normal(38, 4)
                elif condition == "Noise":
                    light_lux = rng.normal(480, 40)
                    noise_db = rng.normal(68, 5)
                else:
                    light_lux = rng.normal(1100, 100)
                    noise_db = rng.normal(68, 5)

                light_lux = max(light_lux, 50)
                noise_db = max(noise_db, 25)

                n_back_level = rng.choice([1, 2])
                difficulty_penalty = 60 if n_back_level == 2 else 0

                fatigue = 0.6 * trial_num

                rt = (
                    p["baseline_speed_ms"]
                    + light_effect_ms(light_lux)
                    + noise_effect_ms(noise_db)
                    + difficulty_penalty
                    + fatigue
                    + rng.normal(0, 55)
                )
                if condition == "Both":
                    rt += 25

                rt = float(np.clip(rt, 280, 2800))

                base_correct_prob = 0.88
                penalty = 0.0005 * noise_effect_ms(noise_db) + 0.0004 * light_effect_ms(light_lux)
                penalty += 0.03 if n_back_level == 2 else 0
                correct_prob = np.clip(base_correct_prob - penalty, 0.55, 0.97)
                correct = int(rng.random() < correct_prob)

                rows.append({
                    "participant_id": p["participant_id"],
                    "age": p["age"],
                    "gender": p["gender"],
                    "condition": condition,
                    "light_lux": round(light_lux, 1),
                    "noise_db": round(noise_db, 1),
                    "n_back_level": n_back_level,
                    "trial_number": trial_num,
                    "reaction_time_ms": round(rt, 1),
                    "correct": correct,
                })
    return pd.DataFrame(rows)


if __name__ == "__main__":
    participants = make_participants(N_PARTICIPANTS)
    trials = simulate_trials(participants)
    trials.to_csv("data/cognitive_environment_synthetic.csv", index=False)
    print("Saved:", trials.shape, "rows x columns ->  data/cognitive_environment_synthetic.csv")
    print(trials.head())
